#!/usr/bin/env node
// Regenerates app/api/**/route.js from the handlers in server/api/**.
//
//   node scripts/gen-app-routes.js
//
// Each API handler is a pages-style `handler(req, res)` living in server/api; the App
// Router serves it through lib/route-adapter.js. Adding an endpoint = write the handler
// in server/api, then run this. Paths map the way pages/api did:
//   server/api/projects/index.js         → /api/projects
//   server/api/projects/[slug]/epics.js  → /api/projects/[slug]/epics
// A route.js whose handler no longer exists is removed.
const fs = require('fs')
const path = require('path')

const root = path.join(__dirname, '..')
const srcRoot = path.join(root, 'server/api')
const outRoot = path.join(root, 'app/api')

function walk(dir, out = []) {
  for (const f of fs.readdirSync(dir)) {
    const p = path.join(dir, f)
    if (fs.statSync(p).isDirectory()) walk(p, out)
    else if (p.endsWith('.js')) out.push(p)
  }
  return out
}

const rel = (from, to) => { const r = path.relative(from, to).split(path.sep).join('/'); return r.startsWith('.') ? r : './' + r }

const wanted = new Map()
for (const file of walk(srcRoot).sort()) {
  const route = path.relative(srcRoot, file).replace(/\.js$/, '').replace(/(^|[/\\])index$/, '')
  const dir = path.join(outRoot, route)
  if (wanted.has(dir)) throw new Error(`Two handlers map to the same route: ${file} and ${wanted.get(dir)}`)
  wanted.set(dir, file)
}

let written = 0
for (const [dir, file] of wanted) {
  fs.mkdirSync(dir, { recursive: true })
  const body = `// Generated by scripts/gen-app-routes.js — edit server/api/${path.relative(srcRoot, file).split(path.sep).join('/')} instead.
import handler from '${rel(dir, file)}'
import { routeHandlers } from '${rel(dir, path.join(root, 'lib/route-adapter.js'))}'

export const dynamic = 'force-dynamic'
export const runtime = 'nodejs'

const h = routeHandlers(handler)
export const GET = h.GET
export const HEAD = h.HEAD
export const POST = h.POST
export const PUT = h.PUT
export const PATCH = h.PATCH
export const DELETE = h.DELETE
export const OPTIONS = h.OPTIONS
`
  const target = path.join(dir, 'route.js')
  if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== body) { fs.writeFileSync(target, body); written++ }
}

// Drop routes whose handler was deleted.
let removed = 0
for (const file of fs.existsSync(outRoot) ? walk(outRoot) : []) {
  if (path.basename(file) !== 'route.js') continue
  if (!wanted.has(path.dirname(file))) { fs.unlinkSync(file); removed++ }
}

console.log(`${wanted.size} routes (${written} written, ${removed} removed)`)
